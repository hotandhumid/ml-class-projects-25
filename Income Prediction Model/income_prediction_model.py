# Libraries!
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
from sklearn.model_selection import train_test_split, RandomizedSearchCV, cross_val_score
from sklearn.preprocessing import LabelEncoder, StandardScaler
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import accuracy_score, classification_report, confusion_matrix
import numpy as np
from scipy.stats import randint

# Load dataset with error handling
file_path = 'AdultIncome.csv'
try:
    data = pd.read_csv(file_path)
    print("Dataset loaded successfully.")
except FileNotFoundError:
    print("Error: File not found. Please ensure the file path is correct.")
    exit()

# Data cleaning
data.replace('?', pd.NA, inplace=True)  # Replace '?' -> NaN
data.dropna(inplace=True)  # Drop rows with missing values
print("Data shape after cleaning:", data.shape)

# Visualizations
plt.figure(figsize=(8, 6))
sns.countplot(x='income', data=data)
plt.title('Income Distribution')
plt.xlabel('Income Level')
plt.ylabel('Count')
plt.show()

plt.figure(figsize=(12, 6))
sns.countplot(x='education', hue='income', data=data, order=data['education'].value_counts().index)
plt.xticks(rotation=45)
plt.title('Income by Education Level')
plt.xlabel('Education Level')
plt.ylabel('Count')
plt.legend(title='Income')
plt.show()

plt.figure(figsize=(10, 6))
sns.histplot(data=data, x='age', hue='income', kde=True, multiple="stack", bins=30)
